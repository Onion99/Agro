package com.google.ai.edge.litertlm

/**
 * 采样器配置 (LLM 文本生成采样策略)
 *
 * 用于控制大模型在解码生成文本时的随机性、多样性与创造力。
 *
 * @property topK Top-K 采样：限制每一步只从概率最高的前 K 个候选 Token 中筛选。
 *                 - 较小值 (如 10-20)：生成更稳定、聚焦，减少离谱词出现；
 *                 - 较大值 (如 40-100)：词汇更丰富；
 *                 - 若为 1 则等同于贪婪采样 (Greedy Search)。
 *
 * @property topP Top-P (核采样 / Nucleus Sampling)：动态选取累积概率达到 P 的候选词集合。
 *                 - 取值范围通常为 (0.0, 1.0]，默认 0.9；
 *                 - 自适应筛选：高确信度时候选集极小，低确信度时候选集变大；
 *                 - 调小更确定集中，调大更具词汇多样性。
 *
 * @property temperature 温度系数：控制概率分布的平滑度，决定输出的随机性与发散程度。
 *                 - 范围一般在 [0.0, 2.0]，默认 0.8；
 *                 - 较低值 (如 0.1~0.3)：输出严谨、确定、逻辑性强，适合代码、事实问答；
 *                 - 中等值 (如 0.7~1.0)：平衡创造力与连贯性，适合常规对话；
 *                 - 较高值 (> 1.0)：更具想象力与发散性，但过高可能胡言乱语。
 *
 * @property seed 随机数种子：用于复现生成结果。
 *                 - 固定相同种子并在其他参数与提示词不变时，输出可保持一致；
 *                 - 设为 0 或默认时通常采用随机种子。
 */
data class SamplerConfig(
    val topK: Int = 40,
    val topP: Double = 0.9,
    val temperature: Double = 0.8,
    val seed: Int = 0
)

